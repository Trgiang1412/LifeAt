const STORAGE_KEY_ASKED_IDS = 'lifeat_english_asked_ids_v3';
const inMemoryAskedIds = new Set<string>();

function loadAskedIds(): Set<string> {
  if (typeof window === 'undefined') return inMemoryAskedIds;
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY_ASKED_IDS);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed)) {
        parsed.forEach((id) => inMemoryAskedIds.add(String(id)));
      }
    }
  } catch {
    // ignore storage errors
  }
  return inMemoryAskedIds;
}

export function markQuestionAsAsked(questionId: string): void {
  inMemoryAskedIds.add(questionId);
  if (typeof window === 'undefined') return;
  try {
    // Giữ tối đa 150 câu gần nhất để tự động xoay vòng khi người chơi đã làm hết sạch kho
    const arr = Array.from(inMemoryAskedIds).slice(-150);
    window.localStorage.setItem(STORAGE_KEY_ASKED_IDS, JSON.stringify(arr));
  } catch {
    // ignore
  }
}

export function resetAskedQuestionsHistory(): void {
  inMemoryAskedIds.clear();
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.removeItem(STORAGE_KEY_ASKED_IDS);
    } catch {}
  }
}

/**
 * Thuật toán xáo trộn mảng Fisher-Yates chuẩn xác 100% ngẫu nhiên
 */
export function shuffleArray<T>(items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

/**
 * Lấy 1 câu hỏi ngẫu nhiên KHÔNG TRÙNG LẶP từ kho Đa Nguồn,
 * ưu tiên theo nguồn (sourceFilter) và chủ đề của NPC (preferredCategories)
 */
export function pickNonRepeatingMultiSourceQuestion(options?: {
  sourceFilter?: EnglishDatabaseSourceId | 'ALL';
  preferredCategories?: MultiSourceEnglishItem['category'][];
  excludeId?: string;
  externalPool?: MultiSourceEnglishItem[];
}): MultiSourceEnglishItem {
  const asked = loadAskedIds();
  const fullPool = [
    ...MULTI_SOURCE_ENGLISH_BANK,
    ...(options?.externalPool || []),
  ];

  // 1. Lọc theo nguồn dữ liệu nếu người chơi chọn nguồn cụ thể
  let candidates =
    options?.sourceFilter && options.sourceFilter !== 'ALL'
      ? fullPool.filter((q) => q.sourceId === options.sourceFilter)
      : fullPool;

  if (candidates.length === 0) {
    candidates = fullPool;
  }

  // 2. Loại trừ câu vừa mới hiển thị tức thì
  if (options?.excludeId && candidates.length > 1) {
    candidates = candidates.filter((q) => q.id !== options.excludeId);
  }

  // 3. Ưu tiên các câu CHƯA TỪNG HỎI trong phiên chơi & thuộc chủ đề của NPC (70% theo chủ đề NPC, 30% mở rộng đa chủ đề để luôn mới mẻ)
  const unaskedAll = candidates.filter((q) => !asked.has(q.id));

  let targetPool: MultiSourceEnglishItem[] = [];
  if (
    options?.preferredCategories &&
    options.preferredCategories.length > 0 &&
    Math.random() < 0.65
  ) {
    const unaskedByCat = unaskedAll.filter((q) =>
      options.preferredCategories!.includes(q.category)
    );
    if (unaskedByCat.length > 0) {
      targetPool = unaskedByCat;
    }
  }

  if (targetPool.length === 0) {
    targetPool = unaskedAll;
  }

  // Nếu người chơi đã trả lời hết toàn bộ các câu trong bộ lọc hiện tại -> Reset lịch sử của nhóm này để bắt đầu vòng mới
  if (targetPool.length === 0) {
    candidates.forEach((q) => inMemoryAskedIds.delete(q.id));
    targetPool = candidates;
  }

  const shuffled = shuffleArray(targetPool);
  const chosen = shuffled[0] || MULTI_SOURCE_ENGLISH_BANK[0];
  markQuestionAsAsked(chosen.id);
  return chosen;
}
